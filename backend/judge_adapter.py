"""judge_adapter.py - the organisers' single connection point (check definitions, "Единый способ подключения").

Working directory: ``backend/`` (in the container: ``/app/backend``, where ``PYTHONPATH`` already points at
``src``). Locally: ``cd backend && PYTHONPATH=src python3 -c "import judge_adapter"``.

    generate_episode(seed, config, output_dir)   team generator -> <output_dir>/public/* + private/{truth,provenance}.json
    make_env()                                   -> object with reset(seed, config) and step(action)
    score_episode(episode_dir, findings, inspection_steps) -> {tp, fp, fn, precision, recall, f1, return}

This module only translates envelopes and names; it never chooses actions and never changes the task:

* ``reset(seed, config)``
    - ``config={"mode": "closed", "episode_dir": <dir>, ...}``: loads exactly that episode in closed mode. The
      grader runs in a separate process (audit_env.grader, ``python -m audit_env.grader``); this process only
      ever receives the public records. Rewards returned to the caller are 0, info is empty. True grades go to
      the grader log (``$AUDIT_ENV_GRADER_LOG``, default ``<tmp>/audit_env_judge/grader_log.jsonl``).
    - ``config={"mode": "train", "episode_dir": <dir>}``: the same episode with the terminal reward returned.
    - ``config={"mode": "train", "team_config": {...}}`` (no episode_dir): generated by the team generator from
      ``seed`` and ``team_config`` (a config like ``configs/*/*.json``; ``{}`` = defaults).
    A repeated reset restarts the episode from scratch.
* ``step({"name": <action>, "args": {...}})`` with the five names of the case. ``submit`` takes
  ``{"findings": <findings.json object: {"episode_id", "findings": [...]}>}`` (a bare list is wrapped with the
  current episode_id).
* Observations: first ``{"task", "manifest", "policy", "remaining_steps"}``; then
  ``{"result", "error", "remaining_steps"}``. Results: list_records -> ``{"records", "next_cursor"}``;
  get_record / get_document -> the record or document object; calculator -> decimal string;
  submit -> ``{"accepted": true}`` or a bounded structure error (never anything about correctness).
  Errors are ``{"code", "message"}`` with fixed public codes (see schemas/observation.schema.json).
* Tables: ``ledger``, ``invoices``, ``payments``, ``fx``; record fields as in schemas/records.schema.json.
* Error types: ``duplicate_invoice``, ``payment_allocation``, ``fx_error``, ``period_cutoff`` (README table).
* inspection_steps = every step before submit, including errors; submit is one of the 100 actions but not
  an inspection step. 100 actions without submit -> truncated with empty findings. 60 s per episode from reset.
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path
from typing import Optional

from audit_env.env import AuditEnv
from audit_env.generator import generate_episode as _generate
from audit_env.generator import load_private, load_public, write_episode
from audit_env.grader import Grader
from audit_env.matcher import SubmissionError, validate_submission

METRIC_KEYS = ("tp", "fp", "fn", "precision", "recall", "f1")
INVALID_SUBMISSION = {"code": "invalid_submission", "message": "Submission structure is invalid; the episode ended."}


def grader_log_path() -> Path:
    default = Path(tempfile.gettempdir()) / "audit_env_judge" / "grader_log.jsonl"
    return Path(os.environ.get("AUDIT_ENV_GRADER_LOG", default))


# --------------------------------------------------------------------------- generation and scoring (jury side)


def generate_episode(seed: int, config: dict, output_dir: str) -> None:
    """Write one episode from the team generator: ``config`` is a generator config (``{}`` = defaults)."""
    write_episode(_generate(seed, config or None), Path(output_dir))


def _as_submission(findings, episode_id: str):
    if isinstance(findings, list):
        return {"episode_id": episode_id, "findings": findings}
    if isinstance(findings, dict) and set(findings) == {"findings"}:
        return {"episode_id": episode_id, **findings}
    return findings


def score_episode(episode_dir: str, findings: dict, inspection_steps: int) -> dict:
    """Closed grader call: metrics + return for a valid submission; return -1 and null metrics otherwise."""
    d = Path(episode_dir)
    public = load_public(d)
    truth, _ = load_private(d)
    sub = _as_submission(findings, public["manifest"]["episode_id"])
    res = Grader(public, truth, grader_log_path()).grade(sub, inspection_steps, "submit")
    if not res["valid"]:
        return {**{k: None for k in METRIC_KEYS}, "return": -1.0}
    return {**{k: res[k] for k in METRIC_KEYS}, "return": res["reward"]}


# --------------------------------------------------------------------------- environment (policy side)


class JudgeEnv:
    def __init__(self):
        self._envs: dict = {}
        self._env: Optional[AuditEnv] = None
        self._mode = "train"
        self._episode_id = ""

    def _inner(self, mode: str) -> AuditEnv:
        if mode not in self._envs:
            self._envs[mode] = AuditEnv("eval", grader_log=grader_log_path()) if mode == "closed" else AuditEnv("train")
        return self._envs[mode]

    def reset(self, seed=None, config: Optional[dict] = None):
        cfg = dict(config or {})
        mode = cfg.get("mode", "train")
        if mode not in ("closed", "train"):
            raise ValueError("config.mode must be 'closed' or 'train'")
        if "episode_dir" in cfg:
            source = {"episode_dir": str(Path(cfg["episode_dir"]).resolve())}
        elif mode == "closed":
            raise ValueError("closed mode needs config.episode_dir")
        else:
            source = cfg.get("team_config") or {}
        self._mode = mode
        self._env = self._inner(mode)
        obs, info = self._env.reset(seed=seed, config=source)
        self._episode_id = obs["manifest"]["episode_id"]
        first = {
            "task": obs["task"],
            "manifest": obs["manifest"],
            "policy": obs["policy"],
            "remaining_steps": obs["steps_remaining"],
        }
        return first, {"mode": mode, "env_version": info["env_version"], "schema_version": info["schema_version"]}

    def step(self, action):
        if self._env is None:
            raise RuntimeError("call reset() before step()")
        native, bad_submit = self._translate(action)
        obs, reward, terminated, truncated, info = self._env.step(native)
        result, error = obs["result"], obs["error"]
        if obs["ok"]:
            tool = native["tool"]
            if tool == "list_records":
                result = {"records": result["records"], "next_cursor": result["next_cursor"]}
            elif tool == "get_document":
                result = result["document"]
            elif tool == "calculator":
                result = result["value"]
            elif tool == "submit":
                result, error = (None, dict(INVALID_SUBMISSION)) if bad_submit else ({"accepted": True}, None)
        out = {"result": result, "error": error, "remaining_steps": obs["steps_remaining"]}
        if self._mode == "closed":
            reward, info = 0.0, {}
        return out, float(reward), bool(terminated), bool(truncated), info

    def _translate(self, action) -> tuple:
        """{"name", "args"} -> the env's {"tool", "args"}; anything malformed passes through to a bounded error."""
        if not isinstance(action, dict) or not isinstance(action.get("name", action.get("tool")), str):
            return action, False
        if set(action) - {"name", "tool", "args"}:
            return {"tool": action.get("name", action.get("tool")), "args": action.get("args"), "_": 1}, False
        name = action.get("name", action.get("tool"))
        args = action.get("args", {})
        if name != "submit":
            return {"tool": name, "args": args}, False
        sub = args.get("findings") if isinstance(args, dict) and set(args) == {"findings"} else args
        sub = _as_submission(sub, self._episode_id)
        try:
            validate_submission(sub, self._episode_id)
            bad = False
        except SubmissionError:
            bad = True  # the env still ends the episode and the grader records -1
        return {"tool": "submit", "args": sub}, bad

    def close(self) -> None:
        for env in self._envs.values():
            env.close()
        self._envs.clear()


def make_env() -> JudgeEnv:
    return JudgeEnv()
